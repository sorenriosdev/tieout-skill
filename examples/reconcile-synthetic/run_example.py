"""Run the synthetic reconcile case end to end and check it against
expected-waterfall.md.

Steps (phases 2 and 3 of the reconcile playbook):
  1. Load a.csv and b.csv into DuckDB.
  2. Ladder L1 to L3: total, per period, per dimension.
  3. U1 at document level, generated by scripts/u1_query.py.
  4. Catalog tests H05, H13 and H16, read from references/hypotheses.md.
  5. Measure effects by neutralizing causes in order (H05, then H13).
  6. Write effects.csv and run scripts/waterfall.py close with the
     tolerances read from spec.md.
  7. Compare the waterfall table with expected-waterfall.md.

Usage: python examples/reconcile-synthetic/run_example.py [--out DIR]
Exit codes: 0 reproduced and closed, 1 anything else.
"""
import argparse
import pathlib
import re
import subprocess
import sys
import tempfile

import duckdb

HERE = pathlib.Path(__file__).resolve().parent
SKILL = HERE.parent.parent / "skills" / "tieout"
CATALOG = SKILL / "references" / "hypotheses.md"
SCRIPTS = SKILL / "scripts"
COLUMNS = ("{'k': 'VARCHAR', 'line': 'INTEGER', 'period': 'VARCHAR', 'typ': 'VARCHAR', "
           "'dim': 'VARCHAR', 'm': 'DECIMAL(18,4)'}")


def connect(**tables):
    """A DuckDB connection where each name is a view over a CSV or a query."""
    con = duckdb.connect()
    for name, source in tables.items():
        if source.endswith(".csv"):
            source = f"SELECT * FROM read_csv('{HERE / source}', header = true, columns = {COLUMNS})"
        con.execute(f"CREATE TABLE {name} AS {source}")
    return con


def catalog_test(tid):
    return re.search(rf"```sql test:{tid}\n(.*?)```", CATALOG.read_text(encoding="utf-8"), re.S).group(1)


def spec_value(label):
    text = (HERE / "spec.md").read_text(encoding="utf-8")
    return re.search(rf"\*\*{re.escape(label)}:\*\* (\S+)", text).group(1)


def total(con, table):
    return con.execute(f"SELECT SUM(m) FROM {table}").fetchone()[0]


def table_rows(markdown):
    return [line for line in markdown.splitlines() if line.startswith("|") or line.startswith("- ")]


def main():
    for stream in (sys.stdout, sys.stderr):  # Windows consoles default to a legacy code page
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", help="folder for effects.csv and waterfall.md (default: a temp folder)")
    out = pathlib.Path(ap.parse_args().out or tempfile.mkdtemp(prefix="tieout-example-"))
    out.mkdir(parents=True, exist_ok=True)

    con = connect(a="a.csv", b="b.csv")
    A, B = total(con, "a"), total(con, "b")
    print(f"L1 total: A = {A}, B = {B}, Δ = {B - A}")
    print("L2 per period:")
    for row in con.execute("""
        SELECT period, SUM(CASE WHEN s = 'a' THEN m END) AS a, SUM(CASE WHEN s = 'b' THEN m END) AS b
        FROM (SELECT 'a' AS s, period, m FROM a UNION ALL SELECT 'b', period, m FROM b)
        GROUP BY period ORDER BY period""").fetchall():
        print(f"  {row[0]}: A = {row[1]}, B = {row[2]}, Δ = {row[2] - row[1]}")
    print("L3 per dimension:")
    for row in con.execute("""
        SELECT dim, SUM(CASE WHEN s = 'a' THEN m END), SUM(CASE WHEN s = 'b' THEN m END)
        FROM (SELECT 'a' AS s, dim, m FROM a UNION ALL SELECT 'b', dim, m FROM b)
        GROUP BY dim ORDER BY dim""").fetchall():
        print(f"  {row[0]}: A = {row[1]}, B = {row[2]}, Δ = {row[2] - row[1]}")

    u1 = subprocess.run([sys.executable, str(SCRIPTS / "u1_query.py"), "--dialect", "duckdb",
                         "--a-table", "a", "--b-table", "b", "--key", "k", "--measure", "m"],
                        capture_output=True, text=True, encoding="utf-8", check=True).stdout
    solo_a, solo_b, comunes, dif = con.execute(u1).fetchone()
    print(f"U1 by document: only in A = {solo_a}, only in B = {solo_b}, common = {comunes}, total = {dif}")
    assert dif == -solo_a + solo_b + comunes, "U1 identity does not hold"

    h05 = con.execute(catalog_test("H05")).fetchone()
    h13 = connect(a="b.csv").execute(catalog_test("H13")).fetchone()   # H13 runs on B's rows
    h16 = con.execute(catalog_test("H16")).fetchone()
    print(f"H05 type filter:        confirmed={h05[0]}, evidence={h05[1]}")
    print(f"H13 source duplicates:  confirmed={h13[0]} (on B), evidence={h13[1]}")
    print(f"H16 rounding exposure:  confirmed={h16[0]} (on A), evidence={h16[1]}")

    # Sequential neutralization: H05 (apply B's type filter to A), then H13 (deduplicate B).
    d0 = B - A
    a1 = total(con, "(SELECT * FROM a WHERE typ IN (SELECT DISTINCT typ FROM b))")
    d1 = B - a1
    b1 = total(con, "(SELECT DISTINCT * FROM b)")
    d2 = b1 - a1
    effects = [("H05", "B keeps only SALE: credit notes missing", d0 - d1, "catalog test H05"),
               ("H13", "Lines repeated in B's source", d1 - d2, "catalog test H13 on B")]
    print(f"Neutralization: Δ0 = {d0}, after H05 = {d1}, after H13 = {d2}")
    assert effects[0][2] == -h05[1], "H05 effect should equal minus the test evidence"
    assert effects[1][2] == h13[1], "H13 effect should equal the test evidence on B"

    effects_csv = out / "effects.csv"
    effects_csv.write_text("id,description,effect,evidence\n"
                           + "".join(f"{i},{d},{e},{ev}\n" for i, d, e, ev in effects), encoding="utf-8")
    wf = subprocess.run([sys.executable, str(SCRIPTS / "waterfall.py"), "close", "--a", str(A), "--b", str(B),
                         "--effects", str(effects_csv), "--eps-abs", spec_value("Absolute tolerance (ε_abs)"),
                         "--eps-rel", spec_value("Relative tolerance (ε_rel)")], capture_output=True, text=True,
                         encoding="utf-8")
    (out / "waterfall.md").write_text(wf.stdout, encoding="utf-8")
    print()
    print(wf.stdout)

    expected = table_rows((HERE / "expected-waterfall.md").read_text(encoding="utf-8"))
    if wf.returncode != 0 or table_rows(wf.stdout) != expected:
        print(f"NOT REPRODUCED: waterfall exit {wf.returncode}; output differs from expected-waterfall.md"
              if wf.returncode == 0 else f"NOT CLOSED: waterfall exit {wf.returncode}")
        sys.exit(1)
    print(f"REPRODUCED: waterfall matches expected-waterfall.md and the case closes. Files in {out}")


if __name__ == "__main__":
    main()
