#!/usr/bin/env python3
"""Generate test U1 (decomposition by key, ladder rungs L4 and L5) for a given
SQL dialect, with your table, key and measure names.

The query is read from the `test:U1` block of references/hypotheses.md, so
what is generated is what tests/test_hypotheses.py verifies. Names are
replaced on the parsed syntax tree and the result is transpiled with sqlglot.
Nothing is translated by hand: without sqlglot this script stops.

Usage:
  python u1_query.py --dialect bigquery --a-table proj.ds.sales_old \
      --b-table proj.ds.sales_new --key order_id --measure amount

Output columns: solo_en_a (only in A), solo_en_b (only in B), dif_en_comunes
(difference on common keys), dif_total. They must satisfy
dif_total = -solo_en_a + solo_en_b + dif_en_comunes; if not, look for NULL keys.

Limitation: one key column. For a composite key, this script refuses rather
than guessing how to combine the columns.

Exit codes: 0 query printed, 2 invalid input or missing sqlglot.
"""
import argparse
import datetime
import pathlib
import re
import sys

CATALOG = pathlib.Path(__file__).resolve().parent.parent / "references" / "hypotheses.md"
BLOCK = re.compile(r"```sql test:U1\n(.*?)```", re.S)


def fail(msg):
    print(f"u1_query: {msg}", file=sys.stderr)
    sys.exit(2)


try:
    import sqlglot
    from sqlglot import exp
except ImportError:
    fail("sqlglot is not installed. It is required to generate U1 for a dialect; "
         "install it (pip install sqlglot) or declare a reduced mode. Do not translate by hand.")


def load_u1():
    match = BLOCK.search(CATALOG.read_text(encoding="utf-8"))
    if not match:
        fail(f"no `test:U1` block found in {CATALOG}")
    return match.group(1)


def parse_column(name, dialect):
    if "," in name:
        fail("composite keys are not supported yet; pass a single key column")
    try:
        node = sqlglot.parse_one(name, read=dialect)
    except sqlglot.errors.ParseError as e:
        fail(f"cannot parse column name {name!r}: {e}")
    if not isinstance(node, exp.Column):
        fail(f"{name!r} is not a plain column name")
    return node


def build(dialect, a_table, b_table, key, measure):
    tree = sqlglot.parse_one(load_u1(), read="duckdb")
    tables = {"a": exp.to_table(a_table, dialect=dialect), "b": exp.to_table(b_table, dialect=dialect)}
    columns = {"k": parse_column(key, dialect), "m": parse_column(measure, dialect)}

    # Only the per-side aggregations read the user's tables; the outer query
    # refers to their output aliases (sa.k, sb.m), which keep the names k and m.
    for select in tree.find_all(exp.Select):
        source = select.args.get("from_") or select.args.get("from")
        table = source.this if source else None
        if not (isinstance(table, exp.Table) and table.name in tables and not table.args.get("db")):
            continue
        alias = table.alias
        new_table = tables[table.name].copy()
        if alias:
            new_table.set("alias", exp.TableAlias(this=exp.to_identifier(alias)))
        table.replace(new_table)
        projections = []
        for proj in select.expressions:
            if isinstance(proj, exp.Column) and not proj.table and proj.name in columns:
                projections.append(exp.alias_(columns[proj.name].copy(), proj.name))
            else:
                projections.append(proj)
        select.set("expressions", projections)
        for col in list(select.find_all(exp.Column)):
            if not col.table and col.name in columns and not isinstance(col.parent, exp.Alias):
                col.replace(columns[col.name].copy())
    return tree.sql(dialect=dialect, pretty=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dialect", required=True, help="sqlglot dialect name, e.g. bigquery, databricks, snowflake, postgres, duckdb, tsql")
    ap.add_argument("--a-table", required=True, help="reference table A (may be qualified)")
    ap.add_argument("--b-table", required=True, help="candidate table B (may be qualified)")
    ap.add_argument("--key", required=True, help="single key column present in both tables")
    ap.add_argument("--measure", required=True, help="measure column present in both tables")
    args = ap.parse_args()
    try:
        sqlglot.Dialect.get_or_raise(args.dialect)
    except ValueError as e:
        fail(str(e))
    sql = build(args.dialect, args.a_table, args.b_table, args.key, args.measure)
    now = datetime.datetime.now().astimezone().isoformat(timespec="seconds")
    print(f"-- Test U1 generated by u1_query.py for {args.dialect} on {now}, sqlglot {sqlglot.__version__}.")
    print("-- Syntax only: run it and check dif_total = -solo_en_a + solo_en_b + dif_en_comunes.")
    print(sql)


if __name__ == "__main__":
    main()
